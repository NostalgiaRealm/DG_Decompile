#!/usr/bin/env python3
"""Inventory native PE inputs and unpack verified UPX copies without editing inputs.

Dependencies: Python 3, pefile and UPX. Reruns reuse only byte-identical binary
outputs and overwrite generated inventory only in directories owned by this tool.
"""
from __future__ import annotations
import argparse
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import struct
import subprocess
import tempfile
import pefile

MARKER = '.prepare_binaries-owned'
ARCH = {0x14c: 'x86', 0x8664: 'x64', 0xaa64: 'ARM64', 0xa641: 'ARM64EC', 0xa64e: 'ARM64X'}

def sha(data):
    return hashlib.sha256(data).hexdigest()

def text(value):
    return value.decode('utf-8', errors='replace') if isinstance(value, bytes) else value

def jsonable(value):
    if isinstance(value, bytes): return {'hex': value.hex(), 'text': text(value)}
    if isinstance(value, dict): return {str(k): jsonable(v) for k,v in value.items()}
    if isinstance(value, (list, tuple)): return [jsonable(v) for v in value]
    return value

def own_directory(path):
    if path.exists() and not (path / MARKER).exists() and any(p.is_file() or p.is_symlink() for p in path.rglob('*')):
        raise RuntimeError(f'Refusing nonempty unowned generated directory: {path}')
    path.mkdir(parents=True, exist_ok=True)
    (path / MARKER).write_text('Generated by scripts/prepare_binaries.py\n')

def save_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(json.dumps(jsonable(value), indent=2) + '\n')
    temporary.replace(path)

def put_binary(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if path.is_symlink() or path.read_bytes() != data:
            raise RuntimeError(f'Refusing to overwrite different binary output: {path}')
        return
    # Exclusive creation also prevents accidentally replacing a concurrent file.
    with path.open('xb') as out: out.write(data)

def command(argv, log_path):
    run = subprocess.run([str(x) for x in argv], stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, errors='replace', timeout=120)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text('$ ' + shlex.join([str(x) for x in argv]) + '\n' + run.stdout
                        + f'\nExit status: {run.returncode}\n')
    return {'argv': [str(x) for x in argv], 'exit_code': run.returncode,
            'output': run.stdout, 'log': str(log_path)}

def table_imports(pe, attribute):
    result=[]
    for module in getattr(pe, attribute, []):
        result.append({'dll': text(module.dll), 'symbols': [
            {'name': text(i.name), 'ordinal': i.ordinal, 'iat_va': i.address,
             'hint': getattr(i, 'hint', None)} for i in module.imports]})
    return result

def metadata(data):
    pe = pefile.PE(data=data, fast_load=False)
    image_base = pe.OPTIONAL_HEADER.ImageBase
    load = getattr(pe, 'DIRECTORY_ENTRY_LOAD_CONFIG', None)
    load_values = ({k: v['Value'] for k,v in load.struct.dump_dict().items()
                    if isinstance(v, dict) and 'Value' in v} if load else {})
    chpe_ptr = load_values.get('CHPEMetadataPointer', 0)
    arch = ARCH.get(pe.FILE_HEADER.Machine, f'unknown-{pe.FILE_HEADER.Machine:#x}')
    if chpe_ptr and pe.FILE_HEADER.Machine == 0x14c:
        arch = 'CHPE x86/ARM64 hybrid'
    elif chpe_ptr and any(s.Name.startswith(b'.a64xrm') for s in pe.sections):
        arch = 'ARM64X hybrid'
    sections = []
    for s in pe.sections:
        sections.append({'name': text(s.Name.rstrip(b'\0')), 'name_hex': s.Name.hex(),
                         'rva': s.VirtualAddress, 'va': image_base+s.VirtualAddress,
                         'virtual_size': s.Misc_VirtualSize,
                         'raw_offset': s.PointerToRawData, 'raw_size': s.SizeOfRawData,
                         'characteristics': s.Characteristics,
                         'readable': bool(s.Characteristics & 0x40000000),
                         'writable': bool(s.Characteristics & 0x80000000),
                         'executable': bool(s.Characteristics & 0x20000000),
                         'entropy': round(s.get_entropy(), 6), 'raw_sha256': sha(s.get_data())})
    exports=[]
    for e in getattr(getattr(pe, 'DIRECTORY_ENTRY_EXPORT', None), 'symbols', []):
        exports.append({'name': text(e.name), 'ordinal': e.ordinal,
                        'rva': e.address, 'va': image_base+e.address,
                        'forwarder': text(e.forwarder)})
    runtime=[]
    directory = pe.OPTIONAL_HEADER.DATA_DIRECTORY[3]
    if directory.VirtualAddress and directory.Size:
        raw = pe.get_data(directory.VirtualAddress, directory.Size)
        width = 12 if pe.FILE_HEADER.Machine == 0x8664 else 8
        for pos in range(0, len(raw)-width+1, width):
            words = struct.unpack_from('<'+'I'*(width//4), raw, pos)
            if not any(words): continue
            record={'table_rva': directory.VirtualAddress+pos, 'raw_hex': raw[pos:pos+width].hex(),
                    'begin_rva': words[0], 'begin_va': image_base+words[0]}
            if width == 12: record.update(end_rva=words[1], unwind_rva=words[2])
            else:
                record.update(unwind_data=words[1], unwind_flag=words[1]&3)
                if words[1]&3 in (1,2): record['packed_function_length_bytes']=((words[1]>>2)&0x7ff)*4
                elif words[1]&3 == 0: record['unwind_info_rva']=words[1]
            runtime.append(record)
    debug=[]
    for item in getattr(pe, 'DIRECTORY_ENTRY_DEBUG', []):
        entry={'type':item.struct.Type,'rva':item.struct.AddressOfRawData,
               'file_offset':item.struct.PointerToRawData,'size':item.struct.SizeOfData}
        raw=data[item.struct.PointerToRawData:item.struct.PointerToRawData+item.struct.SizeOfData]
        entry['raw_hex']=raw.hex()
        if raw.startswith(b'RSDS') and len(raw)>=24:
            entry.update(codeview_kind='RSDS',pdb_path=text(raw[24:].split(b'\0')[0]),
                         guid_raw_hex=raw[4:20].hex(),age=int.from_bytes(raw[20:24],'little'))
        debug.append(entry)
    return {'format':'PE32+' if pe.OPTIONAL_HEADER.Magic==0x20b else 'PE32',
            'architecture':arch, 'machine':pe.FILE_HEADER.Machine,
            'machine_hex':hex(pe.FILE_HEADER.Machine),'is_dll':bool(pe.FILE_HEADER.Characteristics&0x2000),
            'managed_cli':bool(pe.OPTIONAL_HEADER.DATA_DIRECTORY[14].VirtualAddress),
            'image_base':image_base, 'entry_point_rva':pe.OPTIONAL_HEADER.AddressOfEntryPoint,
            'entry_point_va':image_base+pe.OPTIONAL_HEADER.AddressOfEntryPoint,
            'size_of_image':pe.OPTIONAL_HEADER.SizeOfImage, 'pe_timestamp':pe.FILE_HEADER.TimeDateStamp,
            'checksum_header':pe.OPTIONAL_HEADER.CheckSum,'checksum_calculated':pe.generate_checksum(),
            'subsystem':pe.OPTIONAL_HEADER.Subsystem,'characteristics':pe.FILE_HEADER.Characteristics,
            'dll_characteristics':pe.OPTIONAL_HEADER.DllCharacteristics,
            'sections':sections,'imports':table_imports(pe,'DIRECTORY_ENTRY_IMPORT'),
            'delay_imports':table_imports(pe,'DIRECTORY_ENTRY_DELAY_IMPORT'),'exports':exports,
            'load_config':load_values,'load_config_with_offsets':load.struct.dump_dict() if load else None,
            'data_directories':[{'name':d.name,'rva':d.VirtualAddress,'size':d.Size}
                                for d in pe.OPTIONAL_HEADER.DATA_DIRECTORY],
            'runtime_functions':runtime,
            'runtime_function_note':('Raw IMAGE_RUNTIME_FUNCTION_ENTRY records; ARM64 uses 8-byte entries. '
                'For hybrid images these are metadata records, not proof of the instruction set of every range.'),
            'debug':debug, 'parser_warnings':pe.get_warnings()}

def repair_erased_upx(data):
    """Restore only the observed erased UPX names/signature, never code bytes."""
    pe=pefile.PE(data=data, fast_load=True)
    if len(pe.sections)<2: return None, []
    first,second=pe.sections[:2]
    sig_offset=second.PointerToRawData-32
    if (first.Name!=b'\0'*8 or second.Name!=b'\0'*8 or first.SizeOfRawData!=0
        or sig_offset<0 or data[sig_offset:sig_offset+4]!=b'\0'*4):
        return None, []
    work=bytearray(data); changes=[]
    for offset,after,reason in [
        (first.get_file_offset(),b'UPX0\0\0\0\0','Restore erased first section name'),
        (second.get_file_offset(),b'UPX1\0\0\0\0','Restore erased second section name'),
        (sig_offset,b'UPX!','Restore erased pack-header magic at section 1 raw offset minus 32')]:
        before=bytes(work[offset:offset+len(after)])
        changes.append({'offset':offset,'offset_hex':hex(offset),'before_hex':before.hex(),
                        'after_hex':after.hex(),'reason':reason})
        work[offset:offset+len(after)]=after
    return bytes(work), changes

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=Path('/home/rick/Documents/dgVoodoo2_87_5_FIXED'))
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--upx',default=shutil.which('upx'))
    args=parser.parse_args(); source=args.source.resolve(); output=args.output.resolve()
    if source==output or source in output.parents:
        raise SystemExit('Output must be outside the source tree')
    if not args.upx: raise SystemExit('UPX is required to test every PE')
    upx=Path(args.upx).resolve()
    own_directory(output/'inventory'); own_directory(output/'binaries')
    version=command([upx,'--version'],output/'inventory/upx-version.txt')
    records=[]; scan=[]; errors=[]
    all_files=sorted(p for p in source.rglob('*') if p.is_file())
    for path in all_files:
        rel=path.relative_to(source).as_posix()
        if path.is_symlink(): raise RuntimeError(f'Refusing symlink input: {path}')
        data=path.read_bytes(); digest=sha(data)
        found={'path':rel,'size':len(data),'sha256':digest,'has_mz_magic':data[:2]==b'MZ'}
        scan.append(found)
        # Retain the full supplied distribution, including documentation and
        # earlier patch evidence, so the shared bundle can verify itself.
        original=output/'binaries/original'/rel
        put_binary(original,data)
        if data[:2]!=b'MZ':
            found['classification']='non-PE companion'
            if path.suffix.lower() in ('.exe','.dll'):
                errors.append(f'Executable extension without MZ signature: {rel}')
            continue
        try: original_meta=metadata(data)
        except pefile.PEFormatError as exc:
            found['classification']='MZ but PE parse failed'; found['error']=str(exc)
            errors.append(f'PE parse failed: {rel}: {exc}');continue
        found['classification']='PE'
        prepared=output/'binaries/unpacked'/rel
        logs=output/'inventory/upx-logs'/rel
        packing={'original_test':command([upx,'-t',original],logs/'original-test.txt')}
        entry={'path':rel,'source_path':str(path),'original_path':str(original),
               'analysis_path':str(prepared),'prepared_path':prepared.relative_to(output).as_posix(),
               'source_sha256':digest,'source_size':len(data),'packing':packing}
        with tempfile.TemporaryDirectory(prefix='prepare-pe-') as td:
            temporary=Path(td)/path.name; temporary.write_bytes(data)
            work=data; restored,changes=repair_erased_upx(data)
            should_unpack=packing['original_test']['exit_code']==0
            if restored is not None:
                temporary.write_bytes(restored)
                packing['header_restoration']=changes
                packing['header_restored_sha256']=sha(restored)
                restored_out=output/'binaries/header-restored'/rel
                put_binary(restored_out,restored)
                packing['header_restored_path']=str(restored_out)
                packing['restored_test']=command([upx,'-t',temporary],logs/'restored-test.txt')
                if packing['restored_test']['exit_code']!=0:
                    errors.append(f'UPX header restoration did not validate: {rel}')
                should_unpack=packing['restored_test']['exit_code']==0
            if should_unpack:
                packing['unpack']=command([upx,'-d',temporary],logs/'unpack.txt')
                if packing['unpack']['exit_code']!=0:
                    errors.append(f'UPX decompression failed: {rel}')
                else:
                    work=temporary.read_bytes()
                    packing['status']='unpacked (erased header restored)' if changes else 'unpacked'
            else:
                result=packing['original_test']['output']
                if 'NotPackedException' in result: packing['status']='not packed with UPX (UPX test)'
                elif 'UnknownExecutableFormatException' in result:
                    packing['status']='UPX test does not support this PE architecture; normal PE layout inspected'
                else:
                    packing['status']='UPX status unresolved'
                    errors.append(f'UPX status unresolved: {rel}')
            put_binary(prepared,work)
        prepared_meta=metadata(work)
        entry.update(prepared_sha256=sha(work),prepared_size=len(work),
                     architecture=prepared_meta['architecture'],machine=prepared_meta['machine'],
                     metadata_path=f'inventory/metadata/{rel}.json',
                     export_count=len(prepared_meta['exports']),
                     import_count=sum(len(x['symbols']) for x in prepared_meta['imports']),
                     runtime_function_count=len(prepared_meta['runtime_functions']))
        details={'path':rel,'source_sha256':digest,'prepared_sha256':sha(work),**prepared_meta}
        if digest!=sha(work): details['original_packed_metadata']=original_meta
        save_json(output/entry['metadata_path'],details)
        records.append(entry)
        print(f"{rel}: {entry['architecture']}; {packing['status']}",flush=True)
    # Verify ALL original inputs, including companions, after processing.
    source_ok=all(sha((source/item['path']).read_bytes())==item['sha256'] for item in scan)
    if not source_ok: errors.append('Source changed during run')
    manifest={'schema':1,'generated_utc':dt.datetime.now(dt.timezone.utc).isoformat(),
              'source_root':str(source),'output_root':str(output),'pefile_version':pefile.__version__,
              'upx_executable':str(upx),'upx_version':version['output'].splitlines()[0],
              'source_unchanged_verified':source_ok,'scanned_file_count':len(scan),
              'pe_count':len(records),'non_pe_count':len(scan)-len(records),
              'unpacked_count':sum(x['packing']['status'].startswith('unpacked') for x in records),
              'files':records,'errors':errors}
    save_json(output/'inventory/manifest.json',manifest)
    save_json(output/'inventory/all-files.json',scan)
    (output/'inventory/source-sha256.txt').write_text(''.join(f"{x['sha256']}  {x['path']}\n" for x in scan))
    (output/'inventory/analysis-sha256.txt').write_text(''.join(f"{x['prepared_sha256']}  {x['prepared_path']}\n" for x in records))
    lines=['# PE inventory and preparation','',
           f"Scanned **{len(scan)} files** recursively by MZ signature and PE parsing: **{len(records)} PE images**, "
           f"**{len(scan)-len(records)} companion files**. All original input hashes were rechecked after preparation: **{source_ok}**.",
           '',f"Tool versions: `{manifest['upx_version']}` and `pefile {pefile.__version__}`.",
           '', 'The `binaries/original` copies preserve the supplied FIXED input bytes. `binaries/unpacked` contains the analysis inputs, '
           'including byte-identical copies for images already unpacked. Original source files were never written.',
           '', '| Input | Architecture | UPX preparation | Original bytes | Analysis bytes | Exports |',
           '|---|---|---|---:|---:|---:|']
    for x in records:
        lines.append(f"| `{x['path']}` | {x['architecture']} | {x['packing']['status']} | {x['source_size']} | {x['prepared_size']} | {x['export_count']} |")
    lines += ['', '## Reproduce', '', '```sh',
              f"python3 scripts/prepare_binaries.py --source {shlex.quote(str(source))} --output {shlex.quote(str(output))} --upx {shlex.quote(str(upx))}",
              f"(cd {shlex.quote(str(source))} && sha256sum --check {shlex.quote(str(output/'inventory/source-sha256.txt'))})",
              'sha256sum --check inventory/analysis-sha256.txt', '```', '',
              'The script requires Python 3, pefile, and UPX. It refuses conflicting binary outputs and a nonempty unowned generated '
              'directory. Each source file is read and hashed; executable extensions without a valid PE are reported. '
              'UPX test and decompression exit status and full output are retained under `upx-logs/`.', '',
              '## Restoring erased UPX identifiers', '',
              'The supplied `Wine-fix/patch_dgvoodoo_2875.py` already documents restoration of erased identifiers. '
              'For the remaining packed image this run first asserted two empty section names, zero raw size for section 0, '
              'and four zero bytes 32 bytes before section 1 raw data. Only the 8-byte names were changed to `UPX0` and `UPX1` '
              '(zero padded), and the four-byte pack-header magic to `UPX!`. The repaired copy was validated using `upx -t` '
              'before `upx -d` decompressed it. The original, repaired packed copy, and decompressed image are retained separately. '
              'Exact offsets, before/after bytes, hashes, commands, output, and status are in `manifest.json`.', '',
              'For ordinary unpacked images, a negative UPX test means UPX did not recognize its own packing. '
              'For unsupported ARM64 formats it is not proof that no other packer could exist; normal PE sections, imports, '
              'exports, and exception tables remain directly inspectable.', '',
              '## Metadata interpretation', '',
              'Every `metadata/<relative input>.json` contains PE sections and their raw hashes, entropy, permissions, '
              'imports, delay imports, exports, load configuration with file offsets, debug/PDB records, and exception-table '
              'runtime-function records. Addresses explicitly distinguish RVAs from virtual addresses. Timestamp and PDB path '
              'are embedded build metadata, not verified build history. ARM64/CHPE exception records are retained directly; '
              'their presence does not establish instruction-set boundaries in mixed-architecture code. '
              'Each metadata file lists parser warnings rather than silently dropping them.', '',
              f"Preparation errors: {len(errors)}."]
    lines.extend(f'- {e}' for e in errors)
    (output/'inventory/README.md').write_text('\n'.join(lines)+'\n')
    if errors: raise SystemExit('\n'.join(errors))
    print(f'Prepared {len(records)} PE files; sources verified unchanged.',flush=True)

if __name__=='__main__': main()
